// kv_lifecycle_guard.v
// Verilog-2001 boundary for the KV page lifecycle guard.
//
// IP Integrator refuses a SystemVerilog file as a BD module reference
// (ERROR [filemgmt 56-195]). This shim also renames the global signals to
// the AXI spec names ACLK/ARESETn so IPI auto-associates the clock.
//
// The dbg_* ports are NAMED PER-FIELD debug outputs, one ILA probe each,
// so Hardware Manager shows them by name and each can be triggered on
// individually. Generated from the real SV header, never hand-transcribed.

module kv_lifecycle_guard (
  input  wire aclk,
  input  wire aresetn,
  input  wire [11:0] s_axi_awaddr,
  input  wire [2:0] s_axi_awprot,
  input  wire s_axi_awvalid,
  output wire s_axi_awready,
  input  wire [31:0] s_axi_wdata,
