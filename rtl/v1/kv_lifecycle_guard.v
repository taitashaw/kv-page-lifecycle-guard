    .dbg_generation      (dbg_generation),
    .dbg_exp_generation  (dbg_exp_generation),
    .dbg_slot            (dbg_slot),
    .dbg_phys            (dbg_phys),
    .dbg_reuse_req       (dbg_reuse_req),
    .dbg_reuse_grant     (dbg_reuse_grant),
    .dbg_reuse_refused   (dbg_reuse_refused),
    .dbg_stale           (dbg_stale),
    .dbg_payload_mm      (dbg_payload_mm),
    .dbg_evictable       (dbg_evictable),
    .dbg_outstanding     (dbg_outstanding),
    .dbg_ar_wait         (dbg_ar_wait),
    .dbg_rd_latency      (dbg_rd_latency),
    .dbg_rd_latency_max  (dbg_rd_latency_max),
    .dbg_sticky          (dbg_sticky),
    .o_ila_probe         (dbg_probe)
  );

endmodule
