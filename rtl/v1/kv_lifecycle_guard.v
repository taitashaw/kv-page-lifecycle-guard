  output wire [1:0] m_axi_arburst,
  output wire m_axi_arlock,
  output wire [3:0] m_axi_arcache,
  output wire [2:0] m_axi_arprot,
  output wire [3:0] m_axi_arqos,
  output wire m_axi_arvalid,
  input  wire m_axi_arready,
  input  wire [3:0] m_axi_rid,
  input  wire [127:0] m_axi_rdata,
  input  wire [1:0] m_axi_rresp,
  input  wire m_axi_rlast,
  input  wire m_axi_rvalid,
  output wire m_axi_rready,
  output wire dbg_rstn,
  output wire [15:0] dbg_heartbeat,
  output wire [7:0] dbg_refcount,
  output wire [7:0] dbg_reservation,
  output wire [5:0] dbg_inflight,
  output wire [3:0] dbg_fill_pending,
  output wire [7:0] dbg_generation,
  output wire [7:0] dbg_exp_generation,
  output wire [5:0] dbg_slot,
  output wire [5:0] dbg_phys,
  output wire dbg_reuse_req,
  output wire dbg_reuse_grant,
  output wire dbg_reuse_refused,
  output wire dbg_stale,
  output wire dbg_payload_mm,
  output wire dbg_evictable,
  output wire [1:0] dbg_outstanding,
  output wire [15:0] dbg_ar_wait,
  output wire [15:0] dbg_rd_latency,
  output wire [15:0] dbg_rd_latency_max,
  output wire [7:0] dbg_sticky,
  output wire [195:0] dbg_probe
);

  lifecycle_guard_top u_core (
    .clk                 (aclk),
    .rst_n               (aresetn),
    .s_axi_awaddr        (s_axi_awaddr),
    .s_axi_awprot        (s_axi_awprot),
